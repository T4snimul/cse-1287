#include <stdio.h>

int main()
{
  unsigned char x = 5; // 00000101
  printf("%d %d %d", x << 1, x >> 1, x & 3);
  /*
    x ----- 00000101
    x << 1: 00001010 (10)
    x >> 1: 00000010 (2)

    x ----- 00000101
    3 ----- 00000011
    ________________&
            00000001 (1)

    Output: 10 2 1
  */
}
